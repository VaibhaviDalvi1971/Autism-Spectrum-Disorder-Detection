def predict_with_visuals(path, model=None, show_landmarks=True):
    """
    Predict autism from an image or directory of images with visualization

    Parameters:
    - path: Path to image file or directory
    - model: Pre-trained model (will load from file if None)
    - show_landmarks: Whether to show facial landmarks
    """
    # Load model if not provided
    if model is None:
        model = joblib.load("autism_rf_classifier.pkl")

    # Create label encoder with the same classes
    le = LabelEncoder()
    le.classes_ = np.array(["Autistic", "Non_Autistic"])

    def process_file(img_file):
        img = cv2.imread(img_file)
        if img is None:
            print(f"⚠️ Could not read '{img_file}'. Skipping.")
            return

        # Convert to RGB for display and grayscale for processing
        rgb_img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
        gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)

        # Detect face with MTCNN
        results = mtcnn.detect_faces(rgb_img)

        if not results:
            # Try with dlib if MTCNN fails
            faces = detector(gray)
            if not faces:
                print(f"❌ No face detected in '{os.path.basename(img_file)}'.")
                plt.figure(figsize=(6,6))
                plt.imshow(rgb_img)
                plt.title(f"No face detected in {os.path.basename(img_file)}")
                plt.axis('off')
                plt.show()
                return

            face = faces[0]
            x, y, w, h = face.left(), face.top(), face.width(), face.height()

        else:
            # Use MTCNN result
            face_box = results[0]['box']
            x, y, w, h = face_box

        # Ensure coordinates are valid
        x, y = max(0, x), max(0, y)

        # Draw rectangle around face
        vis = rgb_img.copy()
        cv2.rectangle(vis, (x, y), (x + w, y + h), (0, 255, 0), 2)

        # Get facial landmarks
        rect = dlib.rectangle(x, y, x + w, y + h)
        shape = predictor(gray, rect)
        shape_np = face_utils.shape_to_np(shape)

        # Draw landmarks if requested
        if show_landmarks:
            for (x, y) in shape_np:
                cv2.circle(vis, (x, y), 2, (255, 0, 0), -1)

        # Extract features and predict
        feats = extract_features(shape_np).reshape(1, -1)
        pred_idx = model.predict(feats)[0]

        # Get prediction probabilities if available
        if hasattr(model, 'predict_proba'):
            probs = model.predict_proba(feats)[0]
            confidence = probs[pred_idx]
        else:
            confidence = None

        # Get label
        label = le.inverse_transform([pred_idx])[0]

        # Display result
        plt.figure(figsize=(8, 8))
        plt.imshow(vis)

        if confidence:
            plt.title(f"Prediction: {label} (Confidence: {confidence:.2f})", fontsize=14)
        else:
            plt.title(f"Prediction: {label}", fontsize=14)

        plt.axis('off')
        plt.show()

        # Print confidence for each class if available
        if hasattr(model, 'predict_proba'):
            print("Confidence by class:")
            for i, cls in enumerate(le.classes_):
                print(f"  {cls}: {probs[i]:.4f}")

        print("-" * 40)

    # Process single file or directory
    if os.path.isdir(path):
        for fname in sorted(os.listdir(path)):
            if fname.lower().endswith(('.jpg', '.jpeg', '.png', '.bmp')):
                print(f"Processing {fname}...")
                process_file(os.path.join(path, fname))
    else:
        process_file(path)

