# Initialize MTCNN detector for initial face detection
mtcnn = MTCNN()

# Initialize dlib's face detector and landmark predictor for feature extraction
detector = dlib.get_frontal_face_detector()
predictor = dlib.shape_predictor("shape_predictor_68_face_landmarks.dat")

def extract_features(landmarks):
    """
    Extract facial features from landmarks
    Returns a 9-dimensional feature vector
    """
    def euclidean(p1, p2):
        return np.linalg.norm(np.array(p1) - np.array(p2))

    # Extract the relevant facial landmarks
    left_eye = [landmarks[36], landmarks[39]]
    right_eye = [landmarks[42], landmarks[45]]
    nose = landmarks[30]
    mouth = [landmarks[48], landmarks[54]]
    jaw = [landmarks[4], landmarks[12]]

    # Calculate 6 distance features
    features = [
        euclidean(left_eye[0], left_eye[1]),    # Left eye width
        euclidean(right_eye[0], right_eye[1]),  # Right eye width
        euclidean(mouth[0], mouth[1]),          # Mouth width
        euclidean(nose, mouth[0]),              # Nose to left mouth corner
        euclidean(nose, mouth[1]),              # Nose to right mouth corner
        euclidean(jaw[0], jaw[1])               # Jaw width
    ]

    # Calculate 3 ratio features
    left_ear = euclidean(landmarks[37], landmarks[41]) / (features[0] + 1e-6)
    right_ear = euclidean(landmarks[43], landmarks[47]) / (features[1] + 1e-6)
    symmetry_ratio = features[0] / (features[1] + 1e-6)

    # Combine all features
    features.extend([left_ear, right_ear, symmetry_ratio])

    return np.array(features)

def load_and_extract_features(data_dir, categories=["Autistic", "Non_Autistic"]):
    """
    Load images from data_dir and extract facial features
    Returns feature matrix and labels
    """
    feature_matrix = []
    all_labels = []

    for label in categories:
        class_dir = os.path.join(data_dir, label)
        if not os.path.exists(class_dir):
            print(f"Warning: Directory {class_dir} does not exist")
            continue

        print(f"Processing {label} images...")
        for filename in tqdm(os.listdir(class_dir)):
            if not filename.lower().endswith((".jpg", ".png", ".jpeg")):
                continue

            img_path = os.path.join(class_dir, filename)
            try:
                # Read image
                img = cv2.imread(img_path)
                if img is None:
                    print(f"Failed to load image: {img_path}")
                    continue

                # Convert to RGB for MTCNN
                rgb_img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

                # Detect face with MTCNN
                results = mtcnn.detect_faces(rgb_img)
                if not results:
                    # Try with dlib if MTCNN fails
                    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
                    faces = detector(gray)
                    if not faces:
                        print(f"No face detected in: {filename}")
                        continue

                    # Use the first face detected by dlib
                    face = faces[0]
                    shape = predictor(gray, face)
                    shape_np = face_utils.shape_to_np(shape)

                else:
                    # Use MTCNN result
                    face_box = results[0]['box']
                    x, y, w, h = face_box

                    # Ensure coordinates are valid
                    x, y = max(0, x), max(0, y)

                    # Convert to dlib rectangle
                    rect = dlib.rectangle(x, y, x + w, y + h)

                    # Get facial landmarks
                    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
                    shape = predictor(gray, rect)
                    shape_np = face_utils.shape_to_np(shape)

                # Extract features from landmarks
                features = extract_features(shape_np)

                # Add to dataset
                feature_matrix.append(features)
                all_labels.append(label)

            except Exception as e:
                print(f"Error processing {img_path}: {e}")

    return np.array(feature_matrix), np.array(all_labels)

